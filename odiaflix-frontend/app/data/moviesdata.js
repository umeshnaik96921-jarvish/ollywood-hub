// Ye function purani movies ke sath-sath admin panel wali nayi movies ko bhi utha lega
export function getStoredMovies() {
  if (typeof window === "undefined") return MOVIES_LIST;
  try {
    // Yahan "odiaflix_admin_movies" ki jagah "custom_movies" kar do
    const custom = JSON.parse(localStorage.getItem("custom_movies") || "[]");
    return [...custom, ...MOVIES_LIST];
  } catch (e) {
    return MOVIES_LIST;
  }
}